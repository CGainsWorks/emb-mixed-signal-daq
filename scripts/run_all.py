#!/usr/bin/env python3
"""Regenerate every result, document, deck, schematic and fixture.

Order follows the brief: specification, then the noise budget, then the
front end deck and schematic, then the simulated test campaign that a bench
validation would run. Takes about ten seconds.

    python scripts/run_all.py
"""

from __future__ import annotations

import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "model"))
sys.path.insert(0, str(ROOT / "host-tools"))

from daqmodel import campaign, kicad, plots, report, spice  # noqa: E402
from daqmodel import noise_budget as nb  # noqa: E402
from daqmodel.io import write_csv, write_json, write_text  # noqa: E402
from daqmodel.spec import GAINS, SPEC  # noqa: E402

FIL_GAINS = (1, 128)   # gains the firmware in the loop run covers


def step(msg: str) -> None:
    print(f"[{time.perf_counter() - T0:5.1f} s] {msg}", flush=True)


def write_budget(budgets) -> None:
    rows = []
    for b in budgets:
        for name, block, in_deck, dens, rms, share in b.rows:
            rows.append([b.gain_nominal, name, block, "yes" if in_deck else "no",
                         "" if dens != dens else f"{dens:.4f}", f"{rms:.3f}",
                         f"{share * 100:.3f}"])
        rows.append([b.gain_nominal, "TOTAL", "", "", "", f"{b.total_in_vrms * 1e9:.3f}",
                     "100.000"])
    write_csv("test-results/noise-floor/budget.csv",
              ["gain", "contributor", "block", "in_spice_deck",
               "density_nV_rtHz_at_10Hz", "rms_nV", "share_percent"], rows)


def write_fixtures(cals) -> None:
    """C unit test vectors and firmware in the loop inputs."""
    def arr(xs):
        return ", ".join(str(int(x)) for x in xs)

    n_avg = len(cals[0].zero_codes)
    n_spot = len(cals[0].vectors)
    entries = []
    for c in cals:
        gi = GAINS.index(c.gain)
        codes, outs = zip(*c.vectors)
        entries.append(
            f"    {{ /* gain {c.gain} */\n"
            f"        {gi}, {c.vcal_nv}LL, {campaign.full_scale_nv(c.gain)}LL,\n"
            f"        {c.coeffs.offset_q8}LL, {c.coeffs.gain_q29}LL,\n"
            f"        {{{arr(c.zero_codes)}}},\n"
            f"        {{{arr(c.cal_codes)}}},\n"
            f"        {{{arr(codes)}}},\n"
            f"        {{{arr(outs)}}},\n"
            f"    }},")
    text = f"""/*
 * Calibration test vectors from the Python reference implementation, run on
 * the simulated board. Generated by scripts/run_all.py; do not edit.
 */
#ifndef CAL_VECTORS_H
#define CAL_VECTORS_H

#include <stdint.h>

#define CAL_AVG {n_avg}u
#define CAL_SPOT_COUNT {n_spot}u
#define CAL_VECTOR_COUNT {len(cals)}u

typedef struct {{
    unsigned gain_index;
    int64_t vcal_nv;
    int64_t full_scale_nv;
    int64_t offset_q8;
    int64_t gain_q29;
    int32_t zero_codes[CAL_AVG];
    int32_t ref_codes[CAL_AVG];
    int32_t spot_code[CAL_SPOT_COUNT];
    int32_t spot_out[CAL_SPOT_COUNT];
}} cal_vector_t;

static const cal_vector_t cal_vectors[CAL_VECTOR_COUNT] = {{
{chr(10).join(entries)}
}};

#endif"""
    write_text("firmware/test/fixtures/cal_vectors.h", text)


def write_fil_inputs(board, sines) -> None:
    """Code files for the firmware in the loop run, under build/ (not
    committed: they are regenerated on every run and are 100 kB)."""
    import numpy as np
    from daqmodel.sigma_delta import convert

    for s in sines:
        if s.gain not in FIL_GAINS:
            continue
        g = s.gain
        n = 64 + 4   # the firmware averages 64 after discarding 4
        fs = SPEC.full_scale(g)
        from daqmodel.references import instruments
        cal_src, _ = instruments()
        vcal_nv = round(0.9 * fs * 1e9)
        zero = convert(0.0, n, g, board, seed=500 + g).codes
        ref = convert(cal_src.output(vcal_nv * 1e-9), n, g, board, seed=600 + g).codes
        d = Path("build/fil")
        for name, codes in (("zero", zero), ("cal", ref), ("signal", s.codes)):
            write_text(d / f"g{g}_{name}.txt", "\n".join(str(int(c)) for c in np.asarray(codes)))
        write_text(d / f"g{g}_meta.txt", f"{GAINS.index(g)} {vcal_nv} 64 {s.cycles}")


def update_readme(block: str) -> None:
    p = ROOT / "README.md"
    text = p.read_text(encoding="utf-8")
    new, n = re.subn(r"<!-- headline:start.*?<!-- headline:end -->", block, text, flags=re.S)
    if n != 1:
        raise SystemExit("README.md has no headline block")
    with open(p, "w", newline="\n", encoding="utf-8") as h:
        h.write(new)


def main() -> int:
    step("specification")
    write_text("docs/spec.md", report.spec_md())

    step("noise budget")
    budgets = [nb.budget(g) for g in GAINS]
    write_budget(budgets)
    write_text("hardware/docs/noise_budget.md", report.budget_md(budgets))
    plots.budget_psd()
    plots.budget_shares(budgets)

    step("front end: ngspice decks, KiCad schematic, bill of materials")
    spice.write_decks(ROOT / "hardware/spice", GAINS)
    write_text("hardware/kicad/daq_frontend.kicad_sch", kicad.schematic())
    write_text("hardware/kicad/daq.kicad_sym", kicad.symbol_library())
    write_text("hardware/kicad/sym-lib-table", kicad.SYM_LIB_TABLE)
    write_text("hardware/kicad/daq_frontend.kicad_pro", kicad.PROJECT)
    write_csv("hardware/outputs/bom.csv", ["reference", "value", "footprint", "description"],
              kicad.bom_rows())

    board = campaign.board()
    step("noise floor at every gain")
    noise = [campaign.noise_floor(g, board) for g in GAINS]
    write_csv("test-results/noise-floor/noise_floor.csv",
              ["gain", "simulated_uV_rms", "budget_uV_rms", "target_uV_rms",
               "peak_to_peak_uV", "effective_bits", "noise_free_bits", "overloads"],
              [[r.gain, f"{r.floor.rms * 1e6:.4f}", f"{r.budget_vrms * 1e6:.4f}",
                f"{r.target_vrms * 1e6:.3f}", f"{r.floor.peak_to_peak * 1e6:.3f}",
                f"{r.floor.effective_bits:.3f}", f"{r.floor.noise_free_bits:.3f}",
                r.overloads] for r in noise])
    plots.noise_histograms([r for r in noise if r.gain in (1, 128)])

    step("sine tests")
    sines = [campaign.sine_test(g, board) for g in (1, 128)]
    write_csv("test-results/enob-snr/sine.csv",
              ["gain", "freq_Hz", "level_dBFS", "snr_dB", "budget_snr_dB", "thd_dB",
               "sfdr_dB", "sinad_dB", "enob_bits", "enob_ieee1241_bits"],
              [[s.gain, f"{s.f_hz:.4f}", f"{s.m.level_dbfs:.3f}", f"{s.m.snr_db:.3f}",
                f"{s.predicted_snr_db:.3f}", f"{s.m.thd_db:.3f}", f"{s.m.sfdr_db:.3f}",
                f"{s.m.sinad_db:.3f}", f"{s.m.enob_sinad:.3f}", f"{s.m.enob_ieee:.3f}"]
               for s in sines])
    plots.spectra(sines)

    step("linearity sweep")
    lin = campaign.linearity_sweep(1, board)
    write_csv("test-results/linearity/inl.csv",
              ["applied_V", "measured_V", "inl_best_fit_ppm_fsr", "inl_end_point_ppm_fsr"],
              [[f"{a:.7f}", f"{m:.9f}", f"{b:.3f}", f"{e:.3f}"] for a, m, b, e in
               zip(lin.applied, lin.measured, lin.lin.inl_best_fit_ppm,
                   lin.lin.inl_end_point_ppm)])
    plots.inl(lin)

    step("calibration against simulated references")
    cals = [campaign.calibrate_and_validate(g, board) for g in GAINS]
    write_csv("test-results/calibration/coefficients.csv",
              ["gain", "vcal_nV", "offset_q8", "gain_q29"],
              [[c.gain, c.vcal_nv, c.coeffs.offset_q8, c.coeffs.gain_q29] for c in cals])
    rows = []
    for c in cals:
        fsr = SPEC.fsr(c.gain)
        for p in c.points:
            rows.append([c.gain, f"{p.nominal_v:.7f}", f"{p.true_v:.9f}", f"{p.dmm_v:.9f}",
                         f"{p.raw_v:.9f}", f"{p.cal_v:.9f}",
                         f"{(p.raw_v - p.dmm_v) / fsr * 1e6:.2f}",
                         f"{(p.cal_v - p.dmm_v) / fsr * 1e6:.3f}",
                         f"{(p.cal_v - p.true_v) / fsr * 1e6:.3f}"])
    write_csv("test-results/calibration/validation.csv",
              ["gain", "nominal_V", "true_V", "dmm_V", "daq_raw_V", "daq_calibrated_V",
               "raw_error_ppm_fsr", "cal_error_vs_dmm_ppm_fsr", "cal_error_vs_true_ppm_fsr"],
              rows)
    plots.calibration(cals)
    write_fixtures(cals)
    write_fil_inputs(board, sines)

    step("reports")
    write_text("docs/validation_report.md", report.validation_md(board, noise, sines, lin, cals))
    block = report.headline_block(noise, sines, lin, cals)
    update_readme(block)
    write_json("test-results/headline.json", {
        "simulated": True,
        "noise_uV_rms": {str(r.gain): round(r.floor.rms * 1e6, 4) for r in noise},
        "budget_uV_rms": {str(r.gain): round(r.budget_vrms * 1e6, 4) for r in noise},
        "snr_dB_g1": round(sines[0].m.snr_db, 3),
        "thd_dB_g1": round(sines[0].m.thd_db, 3),
        "enob_bits_g1": round(sines[0].m.enob_sinad, 3),
        "inl_ppm_fsr": round(lin.lin.max_best_fit_ppm, 3),
        "cal_error_ppm_fsr_worst": round(max(c.worst_cal_vs_dmm_ppm for c in cals), 3),
    })
    step("done")
    return 0


T0 = time.perf_counter()
if __name__ == "__main__":
    raise SystemExit(main())
