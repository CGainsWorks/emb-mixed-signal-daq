"""ngspice decks for the front end, generated from the netlist.

The deck is what the noise budget is checked against. It is written from
:func:`daqmodel.frontend.netlist`, the same description the KiCad schematic
comes from and ngspice then computes the noise of every resistor itself.
Only the amplifier noise allowances need help, because an ideal amplifier in
SPICE is noiseless:

* Voltage noise: a resistor in series with the non-inverting input whose
  thermal noise equals the allowance, R = e_n^2 / 4kT. The amplifier input
  draws no current, so it changes nothing else.
* Current noise: an isolated resistor to ground whose noise voltage drives a
  voltage controlled current source into the input node. It carries no DC
  and loads nothing.

The amplifiers are VCVS elements with an open loop gain of 1e8, which makes
the closed loop error about 1e-6 at gain 128, far below the agreement asked
of the cross-check. The converter and reference noise are not in the deck;
they are not circuit elements.

ngspice runs at 27 degC by default, the temperature the budget uses.
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np

from .frontend import FRONT_END, FrontEnd, netlist
from .spec import K_BOLTZMANN, TEMPERATURE_K

OPEN_LOOP_GAIN = 1e8

#: Tokens that LTspice accepts and ngspice rejects. A test asserts none of
#: them reaches a generated deck.
LTSPICE_ONLY = ("Rser=", "Lser=", "Cpar=", "IF(", "LIMIT(", ".step")

#: Sweep used for noise and AC analysis.
F_START, F_STOP, POINTS_PER_DECADE = 1.0, 10e6, 40


def _value(v) -> str:
    return v if isinstance(v, str) else f"{v:.6g}"


def deck(gain: int, fe: FrontEnd = FRONT_END, out_dir: str = ".") -> str:
    """The deck for one gain setting.

    ``out_dir`` is where ngspice writes its data files, relative to the
    directory it is run from.
    """
    four_kt = 4 * K_BOLTZMANN * TEMPERATURE_K
    r_en = fe.en_amp ** 2 / four_kt
    r_gen = 1e3
    gm = fe.in_amp / (four_kt * r_gen) ** 0.5

    lines = [
        f"* Front end, nominal gain {gain}. Generated by model/daqmodel/spice.py,",
        "* do not edit by hand: run scripts/run_all.py.",
        "*",
        "* Amplifiers are ideal VCVS; their noise allowances are injected by",
        "* the resistor and VCCS generators marked NOISE below.",
        "VCM src_n 0 DC 0",
    ]
    for p in netlist(gain, fe):
        if p.kind == "VSRC":
            lines.append(f"{p.ref} {p.nets[0]} {p.nets[1]} DC 0 {p.value}")
        elif p.kind in ("R", "C"):
            lines.append(f"{p.ref} {p.nets[0]} {p.nets[1]} {_value(p.value)}")
        elif p.kind == "OPAMP":
            plus, minus, out = p.nets
            n_in = f"ni_{p.ref.lower()}"
            n_gen = f"ng_{p.ref.lower()}"
            lines += [
                f"* {p.ref}: {p.note}, {p.value}",
                f"E{p.ref} {out} 0 {n_in} {minus} {OPEN_LOOP_GAIN:g}",
                f"RNV{p.ref} {plus} {n_in} {r_en:.6g}    ; NOISE e_n "
                f"{fe.en_amp * 1e9:g} nV/rtHz",
                f"RNI{p.ref} {n_gen} 0 {r_gen:g}",
                f"GNI{p.ref} 0 {plus} {n_gen} 0 {gm:.6g}    ; NOISE i_n "
                f"{fe.in_amp * 1e12:g} pA/rtHz",
            ]
        else:
            raise ValueError(p.kind)

    sweep = f"dec {POINTS_PER_DECADE} {F_START:g} {F_STOP:g}"
    d = out_dir.rstrip("/")
    lines += [
        ".control",
        f"noise v(ainp,ainm) VSIG {sweep}",
        "setplot noise1",
        f"wrdata {d}/noise_g{gain}.dat onoise_spectrum",
        f"ac {sweep}",
        "let vd = v(ainp) - v(ainm)",
        f"wrdata {d}/ac_g{gain}.dat mag(vd)",
        "quit",
        ".endc",
        ".end",
    ]
    return "\n".join(lines) + "\n"


def write_decks(directory: Path, gains, fe: FrontEnd = FRONT_END) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    paths = []
    for g in gains:
        p = directory / f"frontend_g{g}.cir"
        with open(p, "w", newline="\n", encoding="utf-8") as h:
            h.write(deck(g, fe, out_dir="spice-out"))
        paths.append(p)
    return paths


def read_wrdata(path: Path) -> tuple[np.ndarray, np.ndarray]:
    """Frequency and value columns from an ngspice ``wrdata`` file.

    ngspice writes the scale and the value in pairs of columns and for a
    complex scale the imaginary part as an extra column, so the first and
    last columns are taken.
    """
    rows = []
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if not parts or not re.match(r"^[-+0-9.]", parts[0]):
            continue
        rows.append((float(parts[0]), float(parts[-1])))
    a = np.array(rows)
    return a[:, 0], a[:, 1]
