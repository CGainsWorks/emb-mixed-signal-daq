def _minus3db() -> float:
    lo, hi = 1.0, SPEC.converter.odr / 2
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if nb.droop_db(mid) > -3.0103:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


