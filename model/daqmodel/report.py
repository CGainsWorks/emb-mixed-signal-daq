def validation_md(board, noise, sines, lin, cals) -> str:
    conv = SPEC.converter
    n_rows = []
    for r in noise:
        n_rows.append(
            f"| {r.gain} | {_uv(r.floor.rms)} | {_uv(r.budget_vrms)} | {_uv(r.target_vrms, 2)} | "
            f"{r.floor.rms / r.budget_vrms:.3f} | {r.floor.effective_bits:.2f} | "
            f"{r.floor.noise_free_bits:.2f} | {_verdict(r.floor.rms <= r.target_vrms)} |")
    s_rows = []
    for s in sines:
        s_rows.append(
            f"| {s.gain} | {s.f_hz:.3f} | {s.m.level_dbfs:.2f} | {s.m.snr_db:.2f} | "
            f"{s.predicted_snr_db:.2f} | {s.m.thd_db:.2f} | {s.m.sfdr_db:.2f} | "
            f"{s.m.sinad_db:.2f} | {s.m.enob_sinad:.2f} | {s.m.enob_ieee:.2f} |")
    s1 = sines[0]
    c_rows = []
    for c in cals:
        c_rows.append(
            f"| {c.gain} | {c.coeffs.offset_q8} | {c.coeffs.gain_q29} | "
            f"{c.worst_raw_ppm:.1f} | {c.worst_cal_vs_dmm_ppm:.2f} | "
            f"{c.worst_cal_vs_true_ppm:.2f} | "
            f"{_verdict(c.worst_cal_vs_dmm_ppm <= SPEC.calibrated_error_target_ppm_fsr)} |")
